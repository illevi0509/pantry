RX=[(CATS.index(c),re.compile(p)) for c,p in RULES]
UNIT={"גרם":"גרם","קילוגרם":'ק"ג',"מיליליטר":'מ"ל',"ליטר":"ליטר","יחידות":"יח'","מטרים":"מטר"}
def cat(n):
    for i,r in RX:
        if r.search(n): return i
    return CATS.index("אחר")
def num(q):
    try: f=float(q)
    except: return None
    if f<=0: return None
    return ("%g"%f)
if __name__=="__main__":
    root=ET.fromstring(gzip.open(sys.argv[1]).read().decode("utf-8-sig"))
    out={}; dist=collections.Counter()
    for it in root.find("Items").findall("Item"):
        g=lambda k:re.sub(r"\s+"," ",(it.findtext(k) or "")).strip()
        code=g("ItemCode")
        if not re.fullmatch(r"\d{7,14}",code): continue
        key=code.lstrip("0")
        name=g("ItemName") or g("ManufactureItemDescription")
        if not name: continue
        q=num(g("Quantity")); u=UNIT.get(g("UnitQty"))
        if g("bIsWeighted")!="1" and q and u and not re.search(r"\d",name) and not (u=="יח'" and q=="1"):
            name=f"{name} {q} {u}"
        c=cat(name); dist[CATS[c]]+=1
        out[key]=[name,c]
    print(len(out)); print(dist.most_common())
    json.dump({"v":1,"source":"חצי חינם, סניף 103, 12.10.2026","cats":CATS,"items":out},open(sys.argv[2],"w",encoding="utf-8"),ensure_ascii=False,separators=(",",":"))
    random.seed(7)
    for k in random.sample(list(out),20): print(k,out[k][0],"→",CATS[out[k][1]])
